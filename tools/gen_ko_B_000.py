def stage(s):
    s = "".join(c for c in s if not 0xE000 <= ord(c) <= 0xF8FF)
    for suf, ko in (("・改変後", "・개변 후"),):
        if s.endswith(suf):
            return stage(s[: -len(suf)]) + ko
    if s in SPECIAL:
        return SPECIAL[s]
    if s.endswith("の戦い"):
        return PLACE[s[:-3]] + " 전투"
    raise KeyError(s)


