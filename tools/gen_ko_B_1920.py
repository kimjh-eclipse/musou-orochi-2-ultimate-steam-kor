def wid(s):
    return sum(0.5 if c == " " else 1 for c in s)


def hard_wrap(s):
    lines, cur = [], ""
    for c in s:
        if c == " " and not cur:
            continue
        if wid(cur + c) > WIDTH:
            lines.append(cur.rstrip())
            cur = "" if c == " " else c
        else:
            cur += c
    lines.append(cur)
    return "\n".join(lines)


def wrap(s, maxlines=99):
    lines, cur = [], ""
    for w in s.split(" "):
        cand = (cur + " " + w) if cur else w
        if wid(cand) <= WIDTH:
            cur = cand
        else:
            if cur:
                lines.append(cur)
            cur = w
    lines.append(cur)
    if len(lines) > maxlines:
        return hard_wrap(s)
    return "\n".join(lines)


