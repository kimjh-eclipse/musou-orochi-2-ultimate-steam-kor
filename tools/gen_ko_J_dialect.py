def main():
    ov = {}
    for p in sorted(glob.glob(str(ROOT / "translation_memory/pc_ko_*.jsonl"))):
        if Path(p).name >= "pc_ko_J_dialect.jsonl":
            continue
        for l in open(p, encoding="utf-8"):
            if l.strip():
                r = json.loads(l)
                ov[r["jp"]] = r["ko"]
    found = {}
    for l in (ROOT / "mapping/pc_match.jsonl").open(encoding="utf-8"):
        r = json.loads(l)
        k = (r["entry"], tuple(r["path"]))
        if k in FIX:
            found[k] = (r["jp"], ov.get(r["jp"], r["ko"]))
    missing = set(FIX) - set(found)
    assert not missing, missing
    rows, bad = [], 0
    for k, new in FIX.items():
        jp, old = found[k]
        ko = re.sub(r"\[(C\d|A\d)\]", lambda m: "\x1b" + m.group(1), new).replace("[R]", "\x1bR")
        problems = []
        if ESC.findall(ko) != ESC.findall(old):
            problems.append(f"codes {ESC.findall(old)} vs {ESC.findall(ko)}")
        if ko.count("\n") != old.count("\n"):
            problems.append("newlines")
        if k[0] != 44 and glyphs(ko) > 40:
            problems.append(f"{glyphs(ko)} glyphs")
        if not can_encode(ko):
            problems.append("unencodable " + "".join(c for c in ko if not can_encode(c)))
        if problems:
            bad += 1
            print("PROBLEM", k, problems, repr(ko))
        rows.append({"jp": jp, "ko": ko})
    if bad:
        sys.exit(f"{bad} problems")
    out = ROOT / "translation_memory/pc_ko_J_dialect.jsonl"
    out.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    print(len(rows), "rows ->", out.name)


if __name__ == "__main__":
    main()
